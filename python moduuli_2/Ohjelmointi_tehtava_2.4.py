#Ohjelmointi tehtävä 2.4: summa, tulo ja keskiarvo

luku1=int(input("Anna ensinmäinen luku: "))
luku2=int(input("Anna toinen luku: "))
luku3=int(input("Anna kolmas luku: "))

summa=luku1 + luku2 + luku3
tulo= luku1 * luku2 * luku3
keskiarvo=(luku1 + luku2 + luku3)*3

print(f"Lukujen summa: {summa}")
print(f"Lukujen tulo: {tulo}")
print(f"Lukujen keskiarvo: {keskiarvo}")